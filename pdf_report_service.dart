import 'dart:typed_data';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import '../models/cricket_models.dart';

class PdfReportService {
  Future<Uint8List> buildReport({
    required String matchTitle,
    required String venue,
    required DateTime date,
    required String result,
    required List<Batter> batting,
    required List<Bowler> bowling,
    required int totalRuns,
    required int wickets,
    required int legalBalls,
    required int extras,
    required List<AwardCandidate> awards,
  }) async {
    final doc = pw.Document();
    doc.addPage(pw.MultiPage(
      pageFormat: PdfPageFormat.a4,
      build: (context) => [
        pw.Text('GULLY CRICKET',
            style: pw.TextStyle(fontSize: 24, fontWeight: pw.FontWeight.bold)),
        pw.SizedBox(height: 5),
        pw.Text(matchTitle, style: const pw.TextStyle(fontSize: 17)),
        pw.Text('$venue  •  ${date.toLocal()}'),
        pw.Divider(),
        pw.Text(result, style: pw.TextStyle(
            fontSize: 16, fontWeight: pw.FontWeight.bold)),
        pw.SizedBox(height: 8),
        pw.Text('INNINGS SUMMARY',
            style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        pw.Text('$totalRuns/$wickets  (${legalBalls ~/ 6}.${legalBalls % 6} overs)'),
        pw.Text('Extras: $extras'),
        pw.SizedBox(height: 12),
        pw.Text('BATTING', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        pw.TableHelper.fromTextArray(
          headers: ['Batter', 'R', 'B', '4s', '6s', 'SR'],
          data: batting.map((b) => [
            b.name, '${b.runs}', '${b.balls}', '${b.fours}', '${b.sixes}',
            b.strikeRate.toStringAsFixed(1)
          ]).toList(),
        ),
        pw.SizedBox(height: 12),
        pw.Text('BOWLING', style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        pw.TableHelper.fromTextArray(
          headers: ['Bowler', 'O', 'W', 'R', 'Econ'],
          data: bowling.map((b) => [
            b.name, b.overs, '${b.wickets}', '${b.runsConceded}',
            b.economy.toStringAsFixed(2)
          ]).toList(),
        ),
        pw.SizedBox(height: 12),
        pw.Text('MATCH AWARDS',
            style: pw.TextStyle(fontWeight: pw.FontWeight.bold)),
        ...awards.map((a) => pw.Padding(
          padding: const pw.EdgeInsets.only(top: 4),
          child: pw.Text('${a.title}: ${a.playerName} — ${a.reason}'),
        )),
        pw.SizedBox(height: 18),
        pw.Text('Generated by Gully Cricket',
            style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey700)),
      ],
    ));
    return doc.save();
  }

  Future<void> share(Uint8List bytes, String filename) async {
    await Printing.sharePdf(bytes: bytes, filename: filename);
  }
}
